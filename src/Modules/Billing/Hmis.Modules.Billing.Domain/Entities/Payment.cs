using Hmis.BuildingBlocks.Domain.Abstractions;
using Hmis.BuildingBlocks.Domain.Entities;
using Hmis.BuildingBlocks.Domain.Exceptions;

namespace Hmis.Modules.Billing.Domain.Entities;

public enum PaymentMethod
{
    Cash,
    Card,
    Bkash,
    Nagad,
    Rocket,
    BankTransfer,

    /// <summary>Taken from the patient's advance deposit (no money changes hands).</summary>
    Advance
}

public enum RefundType
{
    /// <summary>Unused advance returned to the patient.</summary>
    AdvanceReturn,

    /// <summary>All cash received for an invoice returned; the invoice is cancelled when the refund is paid.</summary>
    InvoiceCancellation
}

public enum RefundStatus
{
    Requested,
    Approved,
    Rejected,
    Paid
}

public static class PaymentMethods
{
    /// <summary>Card, mobile banking and bank transfers need the transaction or slip reference.</summary>
    public static bool NeedsReference(PaymentMethod method) => method is not (PaymentMethod.Cash or PaymentMethod.Advance);

    public static void EnsureReference(PaymentMethod method, string? reference)
    {
        if (NeedsReference(method) && string.IsNullOrWhiteSpace(reference))
        {
            throw new DomainException("PAYMENT_REFERENCE_REQUIRED", "Enter the transaction reference for this payment method.");
        }
    }
}

/// <summary>
/// Money received (a receipt): against an invoice, or as an advance deposit when <see cref="InvoiceId"/> is null.
/// Never changed or deleted; mistakes are corrected with refunds.
/// </summary>
[Audited]
public sealed class Payment : AuditableEntity, IAggregateRoot
{
    private Payment() { }

    public string ReceiptNumber { get; private set; } = string.Empty;

    /// <summary>Generated by the client for each payment attempt; a retried submission returns the same receipt.</summary>
    public Guid ClientRequestId { get; private set; }

    public Guid PatientId { get; private set; }
    public Guid? InvoiceId { get; private set; }
    public decimal Amount { get; private set; }
    public PaymentMethod Method { get; private set; }
    public string? Reference { get; private set; }
    public string? Notes { get; private set; }
    public DateTime ReceivedAt { get; private set; }

    public bool IsAdvanceDeposit => InvoiceId is null;

    public static Payment Receive(string receiptNumber, Guid clientRequestId, Guid patientId, Guid? invoiceId, decimal amount,
        PaymentMethod method, string? reference, string? notes, DateTime utcNow)
    {
        if (amount <= 0 || Money.Round(amount) != amount)
        {
            throw new DomainException("PAYMENT_AMOUNT_INVALID", "Enter an amount greater than zero with at most two decimals.");
        }

        if (method == PaymentMethod.Advance && invoiceId is null)
        {
            throw new DomainException("PAYMENT_METHOD_INVALID", "An advance deposit must be paid with cash, card, mobile banking or bank transfer.");
        }

        PaymentMethods.EnsureReference(method, reference);
        return new Payment
        {
            ReceiptNumber = receiptNumber,
            ClientRequestId = clientRequestId,
            PatientId = patientId,
            InvoiceId = invoiceId,
            Amount = amount,
            Method = method,
            Reference = string.IsNullOrWhiteSpace(reference) ? null : reference.Trim(),
            Notes = string.IsNullOrWhiteSpace(notes) ? null : notes.Trim(),
            ReceivedAt = utcNow
        };
    }
}

/// <summary>
/// Money returned to a patient: a separate financial transaction (BRD Module 17 rule 6). Always approved by a
/// Hospital Administrator before the cashier pays it out.
/// </summary>
[Audited]
public sealed class Refund : AuditableEntity, IAggregateRoot, IHasConcurrencyToken
{
    private Refund() { }

    public string RefundNumber { get; private set; } = string.Empty;
    public Guid PatientId { get; private set; }
    public Guid? InvoiceId { get; private set; }
    public RefundType Type { get; private set; }
    public decimal Amount { get; private set; }
    public string Reason { get; private set; } = string.Empty;
    public RefundStatus Status { get; private set; } = RefundStatus.Requested;

    public Guid? DecidedBy { get; private set; }
    public DateTime? DecidedAt { get; private set; }
    public string? DecisionNote { get; private set; }

    public Guid? PaidBy { get; private set; }
    public DateTime? PaidAt { get; private set; }
    public PaymentMethod? Method { get; private set; }
    public string? Reference { get; private set; }

    public uint RowVersion { get; private set; }

    /// <summary>Requested, approved or paid: the money is committed and no longer available as advance.</summary>
    public bool IsCommitted => Status is not RefundStatus.Rejected;

    public static Refund Request(string refundNumber, Guid patientId, Guid? invoiceId, RefundType type, decimal amount, string reason)
    {
        if (amount <= 0 || Money.Round(amount) != amount)
        {
            throw new DomainException("REFUND_AMOUNT_INVALID", "Enter an amount greater than zero with at most two decimals.");
        }

        if ((type == RefundType.InvoiceCancellation) != invoiceId.HasValue)
        {
            throw new DomainException("REFUND_TYPE_INVALID", "A cancellation refund needs an invoice; an advance return must not have one.");
        }

        return new Refund
        {
            RefundNumber = refundNumber,
            PatientId = patientId,
            InvoiceId = invoiceId,
            Type = type,
            Amount = amount,
            Reason = reason.Trim()
        };
    }

    public void Approve(Guid approverId, string? note, DateTime utcNow) => Decide(RefundStatus.Approved, approverId, note, utcNow);

    public void Reject(Guid approverId, string? note, DateTime utcNow) => Decide(RefundStatus.Rejected, approverId, note, utcNow);

    public void MarkPaid(Guid paidBy, PaymentMethod method, string? reference, DateTime utcNow)
    {
        if (Status != RefundStatus.Approved)
        {
            throw new DomainException("REFUND_NOT_APPROVED", Status == RefundStatus.Paid
                ? "This refund has already been paid."
                : "Only an approved refund can be paid out.");
        }

        if (method == PaymentMethod.Advance)
        {
            throw new DomainException("PAYMENT_METHOD_INVALID", "Choose how the money is returned (cash, card, mobile banking or bank transfer).");
        }

        PaymentMethods.EnsureReference(method, reference);
        Status = RefundStatus.Paid;
        PaidBy = paidBy;
        PaidAt = utcNow;
        Method = method;
        Reference = string.IsNullOrWhiteSpace(reference) ? null : reference.Trim();
    }

    private void Decide(RefundStatus status, Guid approverId, string? note, DateTime utcNow)
    {
        if (Status != RefundStatus.Requested)
        {
            throw new DomainException("REFUND_DECIDED", "This refund has already been decided.");
        }

        Status = status;
        DecidedBy = approverId;
        DecidedAt = utcNow;
        DecisionNote = string.IsNullOrWhiteSpace(note) ? null : note.Trim();
    }
}
