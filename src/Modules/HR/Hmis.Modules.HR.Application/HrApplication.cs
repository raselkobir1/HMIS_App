/// <summary>Assembly marker used to register validators and mapping configurations.</summary>
public sealed class HrApplicationMarker;

public static class HrPermissions
{
    public const string Module = "HR";
    public const string EmployeesView = "HR.Employees.View";
    public const string EmployeesManage = "HR.Employees.Manage";
}

/// <summary>Defaults from docs/ROLE-PERMISSION-MATRIX.md §2.</summary>
public sealed class HrPermissionDefinitionProvider : IPermissionDefinitionProvider
{
    public IEnumerable<PermissionDefinition> GetPermissions() =>
    [
        new(HrPermissions.EmployeesView, HrPermissions.Module, "View employees",
            [SystemRoles.HospitalAdministrator, SystemRoles.HrManager, SystemRoles.HospitalOwner]),
        new(HrPermissions.EmployeesManage, HrPermissions.Module, "Register and update employees and their employment status",
            [SystemRoles.HrManager])
    ];
}

/// <summary>Employee codes are generated by the Administration number-sequence service (format editable in Settings).</summary>
public sealed class HrNumberSequences : INumberSequenceDefinitionProvider
{
    public const string EmployeeCode = "EMPLOYEE_CODE";

    public IEnumerable<NumberSequenceDefinition> GetSequences() =>
    [
        new(EmployeeCode, "Employee code", "EMP", "None", 6, "Never")
    ];
}

